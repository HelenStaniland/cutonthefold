/**
 * Splits the source logo PNG into two alpha masks — one per ink colour —
 * so the UI can recolour each layer with a CSS variable and scale it freely.
 * Re-run after replacing public/logo-source.png:  node scripts/build-logo-masks.mjs
 */
import sharp from "sharp";
import { writeFileSync } from "node:fs";

function isBackground(r, g, b, a) {
  if (a < 128) return true;
  const min = Math.min(r, g, b);
  const max = Math.max(r, g, b);
  return min > 205 && max - min < 35;
}

/** Navy — bodice outline, CUT, FOLD */
function isInk(r, g, b, a) {
  if (a < 128 || isBackground(r, g, b, a)) return false;
  return Math.max(r, g, b) < 145;
}

/** Golden-brown — dashed fold line, ON THE */
function isAccent(r, g, b, a) {
  if (a < 128 || isBackground(r, g, b, a)) return false;
  if (isInk(r, g, b, a)) return false;
  const max = Math.max(r, g, b);
  if (max < 90) return false;
  return r > 95 && g > 65 && b < 130 && r > b && g > b * 0.55;
}

/** Alpha mask: classified pixels opaque, everything else transparent. */
function maskRGBA(data, w, h, pick) {
  const out = Buffer.alloc(w * h * 4);
  for (let i = 0; i < w * h; i++) {
    const o = i * 4;
    if (pick(data[o], data[o + 1], data[o + 2], data[o + 3])) {
      out[o] = 0;
      out[o + 1] = 0;
      out[o + 2] = 0;
      out[o + 3] = 255;
    }
  }
  return out;
}

/** Find the widest empty-column gap to split the icon from the wordmark. */
function findIconSplit(data, w, h) {
  const colHasContent = new Array(w).fill(false);
  for (let x = 0; x < w; x++) {
    for (let y = 0; y < h; y++) {
      const o = (y * w + x) * 4;
      const r = data[o];
      const g = data[o + 1];
      const b = data[o + 2];
      const a = data[o + 3];
      if (isInk(r, g, b, a) || isAccent(r, g, b, a)) {
        colHasContent[x] = true;
        break;
      }
    }
  }

  let bestStart = -1;
  let bestLen = 0;
  let runStart = -1;
  // Only consider gaps that begin after the icon has started.
  let seenContent = false;
  for (let x = 0; x < w; x++) {
    if (colHasContent[x]) {
      seenContent = true;
      if (runStart >= 0) {
        const len = x - runStart;
        if (seenContent && len > bestLen) {
          bestLen = len;
          bestStart = runStart;
        }
        runStart = -1;
      }
    } else if (seenContent && runStart < 0) {
      runStart = x;
    }
  }

  if (bestStart < 0) return w;
  return Math.round(bestStart + bestLen / 2);
}

async function writeMask(path, buf, w, h) {
  await sharp(buf, { raw: { width: w, height: h, channels: 4 } })
    .png()
    .toFile(path);
}

const src = "public/logo-source.png";
const trimmed = await sharp(src).trim({ threshold: 12 }).png().toBuffer();
const { data, info } = await sharp(trimmed)
  .ensureAlpha()
  .raw()
  .toBuffer({ resolveWithObject: true });
const { width: w, height: h } = info;

const inkFull = maskRGBA(data, w, h, isInk);
const accentFull = maskRGBA(data, w, h, isAccent);

await writeMask("public/logo-ink-mask.png", inkFull, w, h);
await writeMask("public/logo-fold-mask.png", accentFull, w, h);

const splitX = findIconSplit(data, w, h);
await sharp(inkFull, { raw: { width: w, height: h, channels: 4 } })
  .extract({ left: 0, top: 0, width: splitX, height: h })
  .png()
  .toFile("public/logo-ink-mask-icon.png");
await sharp(accentFull, { raw: { width: w, height: h, channels: 4 } })
  .extract({ left: 0, top: 0, width: splitX, height: h })
  .png()
  .toFile("public/logo-fold-mask-icon.png");

const module = `/** Auto-generated by scripts/build-logo-masks.mjs — do not edit by hand. */
export const LOGO_FULL = {
  ink: "/logo-ink-mask.png",
  fold: "/logo-fold-mask.png",
  width: ${w},
  height: ${h},
} as const;

export const LOGO_ICON = {
  ink: "/logo-ink-mask-icon.png",
  fold: "/logo-fold-mask-icon.png",
  width: ${splitX},
  height: ${h},
} as const;
`;
writeFileSync("app/logoMasks.ts", module);

console.log("Wrote logo masks", {
  width: w,
  height: h,
  iconWidth: splitX,
});
